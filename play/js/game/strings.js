// strings.js: every player-facing word of Monster Bouncer / بودي قارد الوحوش (GAME-SPEC §10) as flat EN + AR dictionaries, plus plural().
// Usage: import { DICT, plural } from './strings.js'; i18n.load(DICT); i18n.t('night', { n: 3 });
//        plural('streak', n) -> '2-day streak' / 'يومين متتاليين' (counted text: always go through plural, not i18n.t).
// Both languages carry the same keys and the same {placeholders}; Arabic is natural Gulf-friendly phrasing with western digits.
// Bidi: in Arabic lines that embed left-to-right runs (dates, scores like 18/20, the daily's '#12') those runs sit inside LRI…PDI (\u2066…\u2069)
// so chat apps and canvas text never reorder them (2026-10-22 must not turn into 22-10-2026, nor '#1' into '1#').
// Plural variants are '<key>_<cat>' keys: EN uses zero|one, AR uses zero|one|two|few (n % 100 in 3..10, plural noun)|many
// (11+, singular noun); a missing variant falls back to the base key (the §10 'streak' base stays the spec text).
// plural() builds a new string: call it when the number changes, not every frame.
// Captions: the tutorial / one-time hint copy lives here under cap_* (tutorial.js reads it through i18n first), and the
// wrong-call lesson under why_*: failHint(rule, guest, wasAdmit, lang) words the one cause of a wrong call ('No hats
// allowed!', 'Exactly 2 eyes!', "Fake hat – doesn't count!", 'It changed in line!', 'It matched the poster!') - call it
// once per wrong verdict. The result line counts CORRECT calls only: result_line 'Sorted right: {a} let in, {b} bounced' (a = correct
// admits, b = correct bounces), result_line_miss adds '{n} walked off' (plural on the missed count).
// Payoff words (the play scene reads them through tutorial.tutorialWord, where this dictionary wins, so they carry the
// same text as tutorial.js's fallback copy): quick (the speed bonus's QUICK!), busted (a trap liar bounced right: its fake
// ripped off), catch (a verdict-flipping shapeshifter called right), lc_perfect (LAST CALL on a Gold night); the night's
// twist (data.nightMod) as mod_<id> + mod_<id>_sub (mod_big_sub takes {n} = the guests), framed by mod_tonight {name}.
// Economy (docs/MONETIZATION.md §11.6): gems / shop / booster / offer keys, iap_<productId> (+ _sub: what it holds; the
// piggy's takes {n} gems inside + {cap}), the piggy's piggy_best {n} {price} / piggy_fill {a} {b} (PIGGY.perPass /
// perGold), the Club Pass's daily gift + run words (pass_gift, pass_gift_day {d} {t}, pass_run {n} {g}, pass_run_rule
// {n} {g}: PASS.run), item_<itemId> for every cosmetic (the 35 outfit names are built from outfit_name), theme_<theme>,
// medal_<id> (+ _sub: the goal), the demo checkout sheet (demo_*, price_demo). Never a word for bribery or gambling.
// Other modules' own keys live in js/game/strings-<key>.js (DICT = { en, ar }); js/main.js merges them over this one.
