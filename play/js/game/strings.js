export const DICT = { en, ar };
export const STRINGS_VERSION = TUNE.version;

const PARAM_RE = /\{(\w+)\}/g;

// plural category of n in lang ('en': zero|one|other, 'ar': zero|one|two|few|many)
export function pluralCat(n, lang) {
  const v = Math.abs(Math.floor(Number(n) || 0));
  if (v === 0) return 'zero';
  if (v === 1) return 'one';
  if (lang !== 'ar') return 'other';
  if (v === 2) return 'two';
  const m = v % 100;
  return m >= 3 && m <= 10 ? 'few' : 'many';
}
function langOf(lang) { return lang && DICT[lang] ? lang : (DICT[i18n.lang] ? i18n.lang : TUNE.fallback); }
// the key to use for n: '<key>_<cat>' when that variant exists in lang, else key itself
export function pluralKey(key, n, lang) {
  const l = langOf(lang), k = key + '_' + pluralCat(n, l);
  return DICT[l][k] !== undefined ? k : key;
}
// the counted text: picks the plural variant for n and fills {n} (= n) plus any params ({a}, {b}, {s}...)
export function plural(key, n, lang, params) {
  const l = langOf(lang), k = pluralKey(key, n, l);
  let s = DICT[l][k];
  if (s === undefined) s = DICT[TUNE.fallback][k];
  if (s === undefined) return key;
  return s.replace(PARAM_RE, (m, name) => {
    const v = params && params[name] !== undefined && params[name] !== null ? params[name] : (name === 'n' ? n : undefined);
    return v === undefined ? m : String(v);
  });
}

// ---- the wrong-call lesson ----
function fill(l, key, params) {
  let s = DICT[l][key];
  if (s === undefined) s = DICT[TUNE.fallback][key];
  if (s === undefined) return '';
  return params ? s.replace(PARAM_RE, (m, name) => (params[name] !== undefined ? String(params[name]) : m)) : s;
}
// the attribute a guest's fake prop is taped on ('' when it wears none)
function fakeAttr(g) {
  const f = g.fake;
  if (!f || !isLiar(g)) return '';
  return f.eyes ? 'eyes' : f.hat ? 'hat' : 'tail';
}
// one clause in words: why_<color|eyes|hat|tail|stripes|dots>_<has|not>
function clauseHint(c, l) {
  const key = 'why_' + (c.attr === 'pattern' ? c.value : c.attr) + (c.has ? '_has' : '_not');
  if (c.attr === 'eyes') return plural(key, c.value, l);
  if (c.attr === 'color') {
    let name = DICT[l]['col_' + c.value] || String(c.value);
    if (l !== 'ar') name = name.toLowerCase();
    return fill(l, key, { color: name });
  }
  return fill(l, key);
}
// failHint(rule, guest, wasAdmit, lang?) -> the caption for a guest judged wrong under `rule` (wasAdmit: it was let in,
// else bounced), in lang (default the current language). One cause, never two that disagree:
//   wrong admit  -> the clause its REAL state breaks (data.firstFail) in words ('No hats allowed!', 'Exactly 2 eyes!'),
//                   or 'Fake hat – doesn't count!' when a trap fake on that very part made it look like a match, or
//                   'It changed in line!' when its shapeshift broke that clause (its old look passed it);
//   wrong bounce -> 'Fake <part> – doesn't count!' when a trap fake made it look wrong, 'It changed in line!' when it
//                   shapeshifted from a look that failed the poster into one that matches, else 'It matched the poster!'.
// A harmless fake or a shift that flipped nothing is never blamed. '' without a rule or guest. Allocates: call it once
// per wrong verdict.
export function failHint(rule, guest, wasAdmit, lang) {
  if (!rule || !rule.clauses || !guest) return '';
  const l = langOf(lang), fa = fakeAttr(guest), sa = guest.shift ? guest.shift.attr : '';
  const trap = fa !== '' && isTrapFake(rule, guest);
  if (wasAdmit) {
    const c = firstFail(rule, guest);
    if (!c) return '';
    if (trap && fa === c.attr) return fill(l, 'why_fake_' + fa);
    if (sa && sa === c.attr && guest.pre && clauseAccepts(c, guest.pre)) return fill(l, 'why_shift');
    return clauseHint(c, l);
  }
  if (trap) return fill(l, 'why_fake_' + fa);
  if (sa && isFlipShift(guest)) return fill(l, 'why_shift');
  return fill(l, 'why_match');
}
