// selfTest(dict?) -> { ok, bad: [key] }: every Arabic value that holds Arabic must START with an Arabic strong character
// ({params} skipped), because text.dir() lays a line out by its first strong character: 'VIP يعطيك ...' would run LTR
// with VIP at the far left end. Values with no Arabic at all ('VIP', '×2') are plain LTR and fine. The dev page runs it
// over this dictionary and strings-economy's.
const AR_CH = /[؀-ۿݐ-ݿࢠ-ࣿﭐ-﷿ﹰ-﻿]/, LATIN_CH = /[A-Za-zÀ-ɏ]/;
export function selfTest(dict) {
  const D = dict || DICT, bad = [];
  const ar = D && D.ar ? D.ar : {};
  for (const k in ar) {
    const v = String(ar[k]).replace(/\{\w+\}/g, '');
    if (!AR_CH.test(v)) continue;
    for (let i = 0; i < v.length; i++) {
      const ch = v[i];
      if (AR_CH.test(ch)) break;
      if (LATIN_CH.test(ch)) { bad.push(k); break; }
    }
  }
  return { ok: bad.length === 0, bad: bad };
}
